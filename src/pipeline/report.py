"""Step 5 — render the markdown triage report (deterministic).

Assembles every required section into a single human-readable report and writes it to
``output/<complaint_id>_triage.md``. The reader should be able to act on the report
without re-reading the original complaint.
"""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import List

from . import llm
from .data_loader import OUTPUT_DIR, TriageContext
from .escalate import Determination
from .schemas import Assessment, Classification, DraftResponse


def write_report(
    ctx: TriageContext,
    classification: Classification,
    escalations: List[Determination],
    draft: DraftResponse,
    assessment: Assessment,
    human_judgment_items: List[str],
) -> Path:
    markdown = render_report(
        ctx, classification, escalations, draft, assessment, human_judgment_items
    )
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUTPUT_DIR / f"{ctx.complaint['complaint_id']}_triage.md"
    path.write_text(markdown, encoding="utf-8")
    return path


def render_report(
    ctx: TriageContext,
    classification: Classification,
    escalations: List[Determination],
    draft: DraftResponse,
    assessment: Assessment,
    human_judgment_items: List[str],
) -> str:
    c = ctx.complaint
    parts: List[str] = []

    parts.append(f"# Complaint Triage Report — {c['complaint_id']}")
    parts.append(
        f"> Generated by the AI Intake Pipeline for {ctx.carrier}. Review before acting — see "
        "**Confidence & Items Requiring Human Judgment** at the end."
    )

    # --- Snapshot -------------------------------------------------------------
    parts.append("## Complaint Snapshot\n")
    parts.append(_kv_table([
        ("Customer", c.get("customer_name")),
        ("Received", f"{c.get('received_date')} via {c.get('received_channel')}"),
        ("Policy #", c.get("policy_number")),
        ("Claim ref", c.get("claim_reference")),
        ("Assigned adjuster", c.get("assigned_adjuster")),
        ("Claim status", c.get("current_claim_status")),
        ("Customer tenure", f"{c.get('customer_tenure_years')} years"),
        ("Prior complaints", c.get("prior_complaints")),
        ("Contact", f"{c.get('customer_phone')} · {c.get('customer_email')}"),
    ]))

    # --- Classification -------------------------------------------------------
    parts.append("## 1. Classification\n")
    parts.append(_kv_table([
        ("Type", _pretty(classification.complaint_type)),
        ("Sentiment", _pretty(classification.sentiment)),
        ("Urgency", _urgency_line(ctx, classification.urgency)),
    ]))
    parts.append(f"\n**Rationale.** {classification.rationale}")
    if classification.evidence_quotes:
        parts.append("\n**Evidence:**")
        parts.extend(f"> {q}" for q in classification.evidence_quotes)

    # --- Escalation -----------------------------------------------------------
    parts.append("\n## 2. Escalation Determination\n")
    for det in escalations:
        parts.append(_render_determination(det))

    # --- Recommended path -----------------------------------------------------
    parts.append("## 3. Recommended Response Path\n")
    parts.append(_kv_table([
        ("Owner", draft.recommended_owner),
        ("Path", draft.recommended_path),
    ]))

    # --- Draft response -------------------------------------------------------
    parts.append("\n## 4. Draft Customer Response\n")
    parts.append("> Draft for review — confirm details before sending.\n")
    parts.append(_blockquote(draft.customer_response))

    # --- Risk -----------------------------------------------------------------
    parts.append("\n## 5. Risk Assessment\n")
    parts.append(assessment.risk_assessment)

    # --- Confidence + human judgment ------------------------------------------
    parts.append("\n## 6. Confidence & Items Requiring Human Judgment\n")
    parts.append(f"**Confidence level: {assessment.confidence_level}**\n")
    if assessment.confidence_reasons:
        parts.extend(f"- {r}" for r in assessment.confidence_reasons)
    parts.append("\n**Items requiring human judgment before action:**\n")
    if human_judgment_items:
        parts.extend(f"- {item}" for item in human_judgment_items)
    else:
        parts.append("- None identified.")

    # --- Footer ---------------------------------------------------------------
    parts.append(
        f"\n---\n*Pipeline: classification & signal extraction on `{llm.HAIKU}`; "
        f"response drafting & risk assessment on `{llm.OPUS}`. "
        f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}.*"
    )

    markdown = "\n".join(parts) + "\n"
    # Guarantee a blank line before every heading so it renders cleanly everywhere.
    return re.sub(r"(?<!\n)\n(#{1,6} )", r"\n\n\1", markdown)


# --- helpers ------------------------------------------------------------------


_STATUS_LABEL = {
    "required": "🔴 **REQUIRED**",
    "needs_review": "🟡 **NEEDS REVIEW**",
    "not_required": "⚪ Not required",
}


def _render_determination(det: Determination) -> str:
    status = _STATUS_LABEL[det.status]
    lines = [f"### {det.category}: {status}\n"]
    if det.fired:
        for trig in det.fired:
            lines.append(f"- **{trig.trigger}**")
            lines.append(f"  - Evidence: {trig.evidence}")
    if det.indeterminate:
        lines.append("\n_Could not be evaluated (needs human review):_")
        for trig in det.indeterminate:
            lines.append(f"- {trig.trigger} — {trig.evidence}")
    if not det.fired and not det.indeterminate:
        lines.append("- No triggers fired.")
    return "\n".join(lines) + "\n"


def _urgency_line(ctx: TriageContext, urgency: str) -> str:
    definition = ctx.routing["urgency_levels"].get(urgency, "")
    return f"{_pretty(urgency)} — {definition}" if definition else _pretty(urgency)


def _kv_table(rows) -> str:
    out = ["| Field | Value |", "| --- | --- |"]
    for key, value in rows:
        out.append(f"| {_escape_cell(key)} | {_escape_cell(value)} |")
    return "\n".join(out)


def _escape_cell(value) -> str:
    """Make a value safe inside a GFM table cell (escape pipes, flatten newlines)."""
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\r", " ").replace("\n", "<br>").strip()


def _blockquote(text: str) -> str:
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


def _pretty(value: str) -> str:
    return value.replace("_", " ").capitalize()
